const languages = ["en", "id", "jp", "kr"];
const langLabels = { en: "EN", id: "ID", jp: "JP", kr: "KR" };
let currentLang = "en";

function switchLanguage(lang) {
    currentLang = lang;
    document.querySelectorAll("[data-lang-key]").forEach(el => {
        const key = el.getAttribute("data-lang-key");
        if (translations[key] && translations[key][lang]) {
            el.innerHTML = translations[key][lang];
        }
    });

    // Update toggle button
    const btn = document.getElementById("lang-toggle");
    if (btn) {
        let html = languages.map(l => {
            if (l === lang) {
                return '<span class="lang-active">' + langLabels[l] + '</span>';
            } else {
                return '<span class="lang-inactive">' + langLabels[l] + '</span>';
            }
        }).join(' / ');
        btn.innerHTML = html;
    }

    // Save preference
    localStorage.setItem("portfolio-lang", lang);
}

document.addEventListener("DOMContentLoaded", function() {
    const savedLang = localStorage.getItem("portfolio-lang") || "en";
    switchLanguage(savedLang);

    const btn = document.getElementById("lang-toggle");
    if (btn) {
        btn.addEventListener("click", function() {
            const currentIndex = languages.indexOf(currentLang);
            const nextIndex = (currentIndex + 1) % languages.length;
            switchLanguage(languages[nextIndex]);
        });
    }
});
